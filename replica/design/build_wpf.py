#!/usr/bin/env python3
"""tokens.json -> src/Lumina/Theme/Tokens.xaml (WPF ResourceDictionary).

    python build_wpf.py            # writes the file
    python build_wpf.py --check    # exits 1 if the file on disk is out of date

Standard library only. Keys are Lumina.<Group>.<PascalName>, e.g. Lumina.Color.SurfaceRaised
(a Color) and Lumina.Brush.SurfaceRaised (a frozen SolidColorBrush).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "tokens.json")
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "src", "Lumina", "Theme", "Tokens.xaml"))
PALETTE = os.path.normpath(os.path.join(HERE, "..", "..", "src", "Lumina", "Theme", "Palette.g.cs"))


def pascal(name):
    return "".join(p.capitalize() for p in name.replace("_", "-").split("-"))


def argb(hex_value):
    h = hex_value.lstrip("#")
    return "#FF" + h.upper()


def render(t):
    L = []
    add = L.append
    add('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"')
    add('                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"')
    add('                    xmlns:sys="clr-namespace:System;assembly=System.Runtime">')
    add("    <!-- GENERATED by replica/design/build_wpf.py from tokens.json. Edit tokens.json, not this file. -->")
    add("")
    for k, v in t["color"].items():
        add(f'    <Color x:Key="Lumina.Color.{pascal(k)}">{argb(v)}</Color>')
    add("")
    for k in t["color"]:
        # every colour brush stays unfrozen so the theme and accent can recolour them at runtime
        add(f'    <SolidColorBrush x:Key="Lumina.Brush.{pascal(k)}" Color="{{StaticResource Lumina.Color.{pascal(k)}}}" />')
    add("")
    for k, v in t["font"].items():
        add(f'    <FontFamily x:Key="Lumina.Font.{pascal(k)}">{v}</FontFamily>')
    add("")
    for k, v in t["type"].items():
        add(f'    <sys:Double x:Key="Lumina.FontSize.{pascal(k)}">{v["size"]}</sys:Double>')
        add(f'    <FontWeight x:Key="Lumina.FontWeight.{pascal(k)}">{v["weight"]}</FontWeight>')
    add("")
    for k, v in t["space"].items():
        add(f'    <sys:Double x:Key="Lumina.Space.{k}">{v}</sys:Double>')
    add("")
    for k, v in t["radius"].items():
        add(f'    <CornerRadius x:Key="Lumina.Radius.{pascal(k)}">{v}</CornerRadius>')
        add(f'    <sys:Double x:Key="Lumina.RadiusValue.{pascal(k)}">{v}</sys:Double>')
    add("")
    for k, v in t["size"].items():
        add(f'    <sys:Double x:Key="Lumina.Size.{pascal(k)}">{v}</sys:Double>')
        add(f'    <GridLength x:Key="Lumina.Grid.{pascal(k)}">{v}</GridLength>')
    add("")
    for k, v in t["motion"].items():
        add(f'    <Duration x:Key="Lumina.Motion.{pascal(k)}">0:0:0.{v:03d}</Duration>')
    add("</ResourceDictionary>")
    return "\n".join(L) + "\n"


def render_palette(t):
    def table(name, colors):
        rows = ",\n".join('        ["%s"] = "%s"' % (k, v.lstrip("#").upper()) for k, v in colors.items())
        return "    public static readonly IReadOnlyDictionary<string, string> %s = new Dictionary<string, string>\n    {\n%s,\n    };\n" % (name, rows)
    dark = t["color"]
    light = dict(dark); light.update(t.get("color-light", {}))
    return ("// GENERATED by replica/design/build_wpf.py from tokens.json. Edit tokens.json, not this file.\n"
            "namespace Lumina.Themes;\n\npublic static class Palette\n{\n" + table("Dark", dark) + "\n" + table("Light", light) + "}\n")


def main():
    with open(SRC, encoding="utf-8") as f:
        text = render(json.load(f))
    with open(SRC, encoding="utf-8") as f:
        pal = render_palette(json.load(f))
    if "--check" in sys.argv:
        old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        oldp = open(PALETTE, encoding="utf-8").read() if os.path.exists(PALETTE) else ""
        if old != text or oldp != pal:
            print("Tokens.xaml or Palette.g.cs is out of date; run build_wpf.py")
            sys.exit(1)
        print("Tokens.xaml and Palette.g.cs are up to date")
        return
    with open(PALETTE, "w", encoding="utf-8", newline="\n") as f:
        f.write(pal)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
