using System.Globalization;
using System.IO;
using System.Text;
using System.Windows.Media;
using Lumina.Settings;
using Lumina.Themes;
using Xunit;

namespace Lumina.Tests;

/// <summary>
/// Measures every colour pair the interface actually uses, for both appearance modes and all nine accents, fails on anything below
/// its WCAG AA target, and rewrites docs/brand/contrast-report.md with the numbers. Nothing in the report is typed by hand.
/// </summary>
public class ContrastReportTests
{
    static Color C(string hex) => (Color)ColorConverter.ConvertFromString("#" + hex.TrimStart('#'));
    static double Ratio(Color a, Color b) => Accent.Contrast(a, b);

    // the player's fixed charcoal (see PALETTES in lumina-osc.lua); the accent sits on top of it
    static readonly Color PlayerBar = C("1B1B1B"), PlayerTrough = C("090909"), PlayerPanel = C("1B1B1B"), PlayerText = C("8F8F8F");

    sealed record Row(string Mode, string Accent, string Pair, double Ratio, double Target)
    {
        public bool Pass => Ratio + 0.0001 >= Target;
    }

    static List<Row> Measure()
    {
        var rows = new List<Row>();
        foreach (var light in new[] { false, true })
        {
            var mode = light ? "Light" : "Dark";
            var pal = light ? Palette.Light : Palette.Dark;
            Color P(string k) => C(pal[k]);
            // the neutral ladder the whole interface is built from
            foreach (var surface in new[] { "bg", "sidebar", "surface", "surface-raised" })
            {
                rows.Add(new(mode, "(base)", $"text on {surface}", Ratio(P("text"), P(surface)), 4.5));
                rows.Add(new(mode, "(base)", $"muted text on {surface}", Ratio(P("text-muted"), P(surface)), 4.5));
            }
            rows.Add(new(mode, "(base)", "faint text on bg", Ratio(P("text-faint"), P("bg")), 4.5));
            rows.Add(new(mode, "(base)", "input border on bg", Ratio(P("border-input"), P("bg")), 3.0));
            rows.Add(new(mode, "(base)", "danger text on surface", Ratio(P("danger"), P("surface")), 4.5));
            rows.Add(new(mode, "(base)", "primary button text", Ratio(P("on-primary"), P("primary")), 4.5));

            foreach (var (hex, name) in Catalog.AccentThemes)
            {
                var (accent, dim, on) = Accent.For(hex, light);
                var fill = Accent.Fill(hex, light);
                foreach (var surface in new[] { "bg", "surface", "surface-raised" })
                {
                    rows.Add(new(mode, name, $"accent text/icon on {surface}", Ratio(accent, P(surface)), 4.5));
                    rows.Add(new(mode, name, $"progress and selection ring on {surface}", Ratio(fill, P(surface)), 3.0));
                }
                rows.Add(new(mode, name, "text on accent fill", Ratio(on, accent), 4.5));
                rows.Add(new(mode, name, "accent glyph on its tint", Ratio(accent, dim), 3.0));
            }
        }

        // the player is dark over the picture in both modes; only the accent changes
        foreach (var (hex, name) in Catalog.AccentThemes)
        {
            var a = C(hex);
            var darkText = Ratio(Colors.Black, a) >= 4.5;
            var onAccent = darkText ? C("0C0D10") : Colors.White;
            rows.Add(new("Player", name, "seek thumb and progress on the trough", Ratio(a, PlayerTrough), 3.0));
            rows.Add(new("Player", name, "icon on the active button", Ratio(onAccent, a), 4.5));
            rows.Add(new("Player", name, "selected row text on the panel", Ratio(a, PlayerPanel), 4.5));
        }
        rows.Add(new("Player", "(base)", "times and icons on the bar", Ratio(PlayerText, PlayerBar), 4.5));
        return rows;
    }

    static string RepoRoot()
    {
        var d = new DirectoryInfo(AppContext.BaseDirectory);
        while (d != null && !File.Exists(Path.Combine(d.FullName, "Lumina.sln"))) d = d.Parent;
        return d?.FullName ?? throw new InvalidOperationException("Lumina.sln not found above " + AppContext.BaseDirectory);
    }

    [Fact]
    public void EveryPairTheInterfaceUsesMeetsItsContrastTargetAndTheReportIsRewritten()
    {
        var rows = Measure();
        var sb = new StringBuilder();
        sb.AppendLine("# Contrast report");
        sb.AppendLine();
        sb.AppendLine("Generated by `tests/Lumina.Tests/ContrastReportTests.cs` from the real palettes and accent code. Do not edit by hand; run the tests to refresh it.");
        sb.AppendLine();
        sb.AppendLine("Targets: WCAG 2.x AA. Text and glyphs that carry meaning 4.5:1; drawn indicators (progress, selection rings, borders of inputs) 3:1.");
        sb.AppendLine("The aperture logo is a fixed asset and does not change with the accent; the accent colours below are what the interface uses.");
        sb.AppendLine();
        sb.AppendLine($"**{rows.Count} pairs measured, {rows.Count(r => !r.Pass)} below target.**");
        sb.AppendLine();
        foreach (var group in rows.GroupBy(r => r.Mode))
        {
            sb.AppendLine($"## {group.Key}");
            sb.AppendLine();
            var worst = group.OrderBy(r => r.Ratio - r.Target).First();
            sb.AppendLine($"Tightest pair: {worst.Accent}, {worst.Pair}: {worst.Ratio.ToString("0.00", CultureInfo.InvariantCulture)}:1 against a target of {worst.Target:0.0}:1.");
            sb.AppendLine();
            sb.AppendLine("| Accent | Pair | Ratio | Target | Result |");
            sb.AppendLine("|---|---|---:|---:|---|");
            foreach (var r in group)
                sb.AppendLine($"| {r.Accent} | {r.Pair} | {r.Ratio.ToString("0.00", CultureInfo.InvariantCulture)} | {r.Target.ToString("0.0", CultureInfo.InvariantCulture)} | {(r.Pass ? "pass" : "FAIL")} |");
            sb.AppendLine();
        }
        var path = Path.Combine(RepoRoot(), "docs", "brand", "contrast-report.md");
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, sb.ToString().Replace("\r\n", "\n"), new UTF8Encoding(false));

        var failing = rows.Where(r => !r.Pass).Select(r => $"{r.Mode} / {r.Accent} / {r.Pair}: {r.Ratio:0.00} (needs {r.Target})").ToList();
        Assert.True(failing.Count == 0, "Below target:\n" + string.Join("\n", failing));
    }
}
