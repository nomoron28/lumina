"""Turns the logos in Logos/ into what the app embeds.

  Logos/imdb@logotyp.us.svg, themoviedatabase.svg  ->  src/Lumina/Theme/RatingLogos.xaml (vector drawings)
  Logos/Screenshot ... .png (Rotten Tomatoes sheet) ->  src/Lumina/Assets/Ratings/rt-{fresh,rotten,hot,stale}.png (transparent)

The source logos in Logos/ are not in the public repository (they belong to IMDb, TMDB and Rotten Tomatoes); the generated
src/Lumina/Theme/RatingLogos.xaml and src/Lumina/Assets/Ratings/*.png are. Only needed to regenerate them.

Run: python scripts/brand/make_rating_logos.py
"""
import glob
import os
import xml.etree.ElementTree as ET

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LOGOS = os.path.join(ROOT, "Logos")
OUT_XAML = os.path.join(ROOT, "src", "Lumina", "Theme", "RatingLogos.xaml")
OUT_PNG = os.path.join(ROOT, "src", "Lumina", "Assets", "Ratings")


def paths(svg):
    root = ET.parse(os.path.join(LOGOS, svg)).getroot()
    inherited = root.get("fill")
    transform = None
    out = []
    for e in root.iter():
        tag = e.tag.split("}")[1]
        if tag == "g" and e.get("transform", "").startswith("matrix("):
            transform = [float(v) for v in e.get("transform")[7:-1].replace(",", " ").split()]
        if tag == "path":
            out.append((e.get("d"), e.get("fill") or inherited or "#000000", e.get("fill-rule") or root.get("fill-rule")))
    return out, transform


def drawing(key, svg):
    ps, m = paths(svg)
    body = []
    for d, fill, rule in ps:
        prefix = "F0 " if rule == "evenodd" else "F1 "
        body.append(f'            <GeometryDrawing Brush="{fill.upper()}" Geometry="{prefix}{d}" />')
    xf = ""
    if m:
        xf = f'<DrawingGroup.Transform><MatrixTransform Matrix="{" ".join(repr(v) for v in m)}" /></DrawingGroup.Transform>'
    inner = "\n".join(body)
    return f'    <DrawingImage x:Key="{key}">\n        <DrawingImage.Drawing>\n            <DrawingGroup>{xf}\n{inner}\n            </DrawingGroup>\n        </DrawingImage.Drawing>\n    </DrawingImage>\n'


xaml = '<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation" xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\n'
xaml += "    <!-- Generated by scripts/brand/make_rating_logos.py from the files in Logos/. Do not edit. -->\n"
xaml += drawing("Lumina.Logo.Imdb", "imdb@logotyp.us.svg") + drawing("Lumina.Logo.Tmdb", "themoviedatabase.svg")
xaml += "</ResourceDictionary>\n"
open(OUT_XAML, "w", encoding="utf8", newline="\r\n").write(xaml)

# Rotten Tomatoes: four marks on one white sheet. Colour-to-alpha against white keeps the soft edges.
sheet = glob.glob(os.path.join(LOGOS, "Screenshot*.png"))[0]
im = Image.open(sheet).convert("RGB")
os.makedirs(OUT_PNG, exist_ok=True)
for name, (x0, x1) in {"fresh": (40, 215), "rotten": (380, 540), "hot": (730, 860), "stale": (1050, 1200)}.items():
    crop = im.crop((x0, 0, x1, 143))
    px = crop.load()
    rgba = Image.new("RGBA", crop.size)
    po = rgba.load()
    for y in range(crop.height):
        for x in range(crop.width):
            r, g, b = px[x, y]
            a = max(255 - r, 255 - g, 255 - b)
            if a < 6:
                po[x, y] = (0, 0, 0, 0)
                continue
            k = a / 255
            po[x, y] = tuple(min(255, max(0, round((c - 255 * (1 - k)) / k))) for c in (r, g, b)) + (a,)
    rgba = rgba.crop(rgba.getbbox())
    rgba.save(os.path.join(OUT_PNG, f"rt-{name}.png"))
    print(name, rgba.size)
print("ok")
